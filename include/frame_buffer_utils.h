#ifndef _WRITE_FRAME_BUFFER_H_
#define _WRITE_FRAME_BUFFER_H_

#include <stdint.h>
#include <stddef.h>

typedef struct {
	uint8_t r;
	uint8_t g;
	uint8_t b;
	uint8_t a;
} Color;

typedef struct {
	// address 
	uint32_t *buffer;
	
	// size of screen
	uint32_t width;
	uint32_t height;
	uint32_t pitch; // width plus padding
	
	// location of colors
	uint8_t red_shift;
	uint8_t green_shift;
	uint8_t blue_shift;
	uint8_t alpha_shift;
} FrameBuffer;

// simple struct to represent a coordinate
typedef struct {
	int32_t x;
	int32_t y;
} Point;

typedef struct {
	Point pixel;
	Color color;
} Pixel;

typedef struct {
	Pixel *pixels;
	size_t capacity;
	size_t count;
} PixelList;

/*
* A function to take a Color struct and pack it into a uint32_t
* 
* @param color - A Color struct representing the color of the pixel
* @param fb - A pointer to the frame buffer the pixel is being drawn on
* @return uint32_t - A 32 bit integer representing the color, formatted correctly for the frame buffer
*/
uint32_t pack_color(Color color, FrameBuffer *fb);

/*
* A function to change the color of a specified pixel in a frame buffer
*
* @param fb - A pointer to the the frame buffer the pixel is being drawn on
* @param point - A Point representing the x and y coordinates of the pixel
* @param color - A Color representing the color of the pixel
*/
void put_pixel(FrameBuffer *fb, Point point, Color color);

/*
* A function to change the color of a specified pixel in a frame buffer. Used when filling many pixels with the same color.
*
* @param fb - A pointer to the frame buffer the pixel is being drawn on
* @param point - A Point representing the x and y coordinates of the pixel
* @param color - A 32 bit integer representing the color of the pixel (likely generated by pack_rgb())
*/
void put_pixel_pre_packed(FrameBuffer *fb, Point point, uint32_t color);

/*
* A function to fill a frame buffer with a specified color
*
* @param fb - A pointer to the frame buffer to fill
* @param color - A Color representing the color to fill the screen with
*/
void clear_screen(FrameBuffer *fb, Color color);

/*
* A function to draw a provided list of pixels to the screen
* 
* @param fb - A pointer to the frame buffer
* @param pixels - A list of Pixels
* @param num_pixels - The length of the pixels list
*/
void draw_pixel_array(FrameBuffer *fb, PixelList *pixels);

/*
* A helper function to clear a PixelList
* 
* @param pixels - The PixelList to clear
*/
void clear_pixel_array(PixelList *pixels);

/*
* A helper function to add a pixel to a PixelList
* 
* @param pixels - The PixelList
* @param point - The Point to add
* @param color - The Color of the Point
* @return int - 1 on success, 0 on failure
*/
int add_pixel_to_array(PixelList *pixels, Point point, Color color);

#endif
